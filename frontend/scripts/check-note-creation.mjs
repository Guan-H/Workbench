import assert from 'node:assert/strict'
import { fileURLToPath } from 'node:url'

/** Real UI creation followed by authenticated persistent reads; no intercepted responses. */
export async function checkNoteCreation(page, request, output) {
  const row = path => page.locator(`.tree-row[data-file-path="${path}"]`)
  const blank = page.getByLabel('文件目录空白区域', { exact: true })
  const root = page.getByRole('button', { name: '根目录 /', exact: true })
  const folderDialog = page.getByRole('dialog', { name: '新建文件夹', exact: true })
  const name = folderDialog.getByLabel('文件夹名称', { exact: true })
  const navigation = page.getByRole('navigation', { name: '主要导航' })
  async function listed() { const response = await request('/notes'); assert.equal(response.status, 200); return response.body.items }
  async function blankMenu() {
    const bounds = await blank.boundingBox()
    await blank.click({ button: 'right', position: { x: bounds.width - 12, y: bounds.height - 12 } })
    await page.getByRole('menuitem', { name: '新建文件夹', exact: true }).waitFor()
  }
  async function inFolder(path, kind = '文件夹') {
    await row(path).click({ button: 'right' })
    const bounds = await page.getByRole('menu').boundingBox()
    assert.ok(bounds.y >= 8 && bounds.y + bounds.height <= 960 - 8, 'folder menu stays in viewport')
    await page.getByRole('menuitem', { name: '在此新建' + kind, exact: true }).click()
  }
  await root.click()
  const before = (await listed()).length
  await blankMenu()
  await page.getByRole('menuitem', { name: '新建文件夹', exact: true }).click()
  await name.waitFor()
  assert.deepEqual(await name.evaluate(element => [document.activeElement === element, element.selectionStart, element.selectionEnd]), [true, 0, '新建文件夹'.length])
  await name.press('Escape')
  await folderDialog.waitFor({ state: 'hidden' })
  assert.equal((await listed()).length, before, 'cancelling does not persist a folder')

  await blankMenu()
  await page.getByRole('menuitem', { name: '新建文件夹', exact: true }).click()
  await name.fill('交互测试')
  for (const [width, height] of [[1440, 960], [375, 812], [812, 375]]) {
    await page.setViewportSize({ width, height })
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    await page.screenshot({ path: fileURLToPath(new URL(`create-folder-${width}.png`, output)), fullPage: true })
  }
  await page.setViewportSize({ width: 1440, height: 960 })
  await name.press('Enter')
  await folderDialog.waitFor({ state: 'hidden' })
  await row('交互测试').waitFor()
  assert.equal(await row('交互测试').getAttribute('aria-pressed'), 'true')
  const parent = (await listed()).find(item => item.path === '交互测试')
  assert.ok(parent && parent.type === 'folder')
  await page.getByRole('button', { name: '收起文件夹：交互测试', exact: true }).click()
  await root.click()
  await page.getByRole('button', { name: '展开文件夹：交互测试', exact: true }).click()
  assert.equal(await root.getAttribute('aria-pressed'), 'true', 'expanding does not change creation location')
  await page.getByRole('button', { name: '收起文件夹：交互测试', exact: true }).click()
  await row('交互测试').click()
  await page.getByRole('button', { name: '展开文件夹：交互测试', exact: true }).waitFor()
  assert.equal(await row('交互测试').getAttribute('aria-pressed'), 'true', 'name selects without expanding')

  await inFolder('交互测试')
  assert.equal(await folderDialog.getByRole('button', { name: '选择创建位置', exact: true }).innerText(), '交互测试')
  await name.fill('坏/名称')
  await name.press('Enter')
  await folderDialog.getByRole('alert').filter({ hasText: '名称不能包含' }).waitFor()
  assert.equal((await listed()).length, before + 1)
  await name.fill('子目录')
  await name.press('Enter')
  await folderDialog.waitFor({ state: 'hidden' })
  await row('交互测试/子目录').waitFor()
  assert.equal(await row('交互测试/子目录').getAttribute('aria-pressed'), 'true')
  assert.equal(await row('交互测试/子目录').evaluate(element => document.activeElement === element), true)
  assert.equal(await row('交互测试').getAttribute('aria-expanded'), 'true')
  await row('交互测试').dblclick()
  await row('交互测试/子目录').waitFor({ state: 'hidden' })
  assert.equal(await row('交互测试').getAttribute('aria-expanded'), 'false', 'double click collapses an expanded folder')
  await row('交互测试').dblclick()
  await row('交互测试/子目录').waitFor()
  assert.equal(await row('交互测试').getAttribute('aria-expanded'), 'true', 'double click expands a collapsed folder')
  await row('交互测试/子目录').click()
  await inFolder('交互测试')
  await name.fill('子目录')
  await name.press('Enter')
  await folderDialog.getByRole('alert').filter({ hasText: '同名' }).waitFor()
  assert.equal(await name.inputValue(), '子目录')
  assert.equal((await listed()).filter(item => item.path === '交互测试/子目录').length, 1)
  await folderDialog.getByRole('button', { name: '取消', exact: true }).click()

  // Empty-space keyboard menu uses the selected folder, while the explicit root always uses root.
  await blank.focus(); await page.keyboard.press('Shift+F10')
  await page.getByRole('menuitem', { name: '新建文件夹', exact: true }).click()
  assert.equal(await folderDialog.getByRole('button', { name: '选择创建位置', exact: true }).innerText(), '交互测试/子目录')
  await folderDialog.getByRole('button', { name: '选择创建位置', exact: true }).click()
  const picker = page.getByRole('dialog', { name: '选择创建位置', exact: true })
  await picker.getByRole('button', { name: '根目录 /', exact: true }).click()
  await picker.getByRole('button', { name: '使用此目录', exact: true }).click()
  await name.fill('界面根目录')
  await name.press('Enter')
  await folderDialog.waitFor({ state: 'hidden' })
  await row('界面根目录').waitFor()
  assert.ok((await listed()).some(item => item.path === '界面根目录'))
  await root.click({ button: 'right' })
  await page.getByRole('menuitem', { name: '新建文件夹', exact: true }).click()
  assert.equal(await folderDialog.getByRole('button', { name: '选择创建位置', exact: true }).innerText(), '根目录 /')
  await name.press('Escape')

  await inFolder('交互测试', '笔记')
  const noteDialog = page.getByRole('dialog', { name: '新建笔记', exact: true })
  await noteDialog.getByLabel('笔记名称', { exact: true }).fill('说明')
  await noteDialog.getByLabel('笔记名称', { exact: true }).press('Enter')
  await noteDialog.waitFor({ state: 'hidden' })
  await row('交互测试/说明.md').waitFor()
  const note = (await listed()).find(item => item.path === '交互测试/说明.md')
  assert.ok(note && note.type === 'note')
  assert.equal((await request('/notes/' + note.id)).body.content, '')
  assert.equal(await page.locator('.tree-row.selected').count(), 1)
  await row('交互测试/子目录').click()
  assert.equal(await page.locator('.tree-row.selected').count(), 1, 'folder replaces the open file highlight')
  assert.equal(await row(note.path).getAttribute('aria-pressed'), 'false')
  assert.equal(await row('交互测试/子目录').getAttribute('aria-pressed'), 'true')
  assert.ok((await page.locator('.document-tab').innerText()).includes('说明.md'), 'folder selection keeps the open note')
  await page.getByTestId('markdown-editor').fill('选择回归\n')
  await page.getByRole('button', { name: '保存笔记', exact: true }).click()
  await page.getByTestId('save-feedback').filter({ hasText: '已保存到服务器' }).waitFor()
  assert.equal(await page.locator('.tree-row.selected').count(), 1)
  assert.equal(await row('交互测试/子目录').getAttribute('aria-pressed'), 'true', 'saving does not reselect the open file')
  await row(note.path).click()
  assert.equal(await page.locator('.tree-row.selected').count(), 1)
  assert.equal(await row(note.path).getAttribute('aria-pressed'), 'true', 'clicking the already open file reselects it')
  assert.equal(await row('交互测试/子目录').getAttribute('aria-pressed'), 'false')
  await root.click()
  assert.equal(await page.locator('.tree-row.selected').count(), 0)
  assert.equal(await root.getAttribute('aria-pressed'), 'true')
  await row(note.path).click()
  assert.equal(await root.getAttribute('aria-pressed'), 'false')
  assert.equal(await page.locator('.tree-row.selected').count(), 1)
  await navigation.getByRole('button', { name: '回收站', exact: true }).click()
  assert.equal(await page.getByRole('button', { name: '新建文件夹', exact: true }).count(), 0)
  await blank.click({ button: 'right' })
  assert.equal(await page.getByRole('menu').count(), 0)
  await page.keyboard.press('Escape')
  await navigation.getByRole('button', { name: '笔记', exact: true }).click()
  return { folderId: parent.id, noteId: note.id, notePath: note.path }
}
